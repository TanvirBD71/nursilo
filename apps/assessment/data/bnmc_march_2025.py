def _truths(true_keys: str) -> str:
    keys = {k.strip().lower() for k in true_keys.replace(",", " ").split() if k.strip()}
    return ",".join(
        f"{letter.upper()}={'TRUE' if letter in keys else 'FALSE'}"
        for letter in ("a", "b", "c", "d", "e")
    )


def _tf(num, page, stem, a, b, c, d, e, true_keys, *, subject="", topic="", scenario=""):
    return {
        **_REQUIRED_BLANK,
        "question_code": f"BNMC-2025-03-TF-{num:03d}",
        "question_type": "TRUE/FALSE",
        "question_text": stem,
        "scenario": scenario,
        "option_a": a,
        "option_b": b,
        "option_c": c,
        "option_d": d,
        "option_e": e,
        "correct_answer": _truths(true_keys),
        "subject": subject,
        "topic": topic,
        "scenario_based": "true" if scenario else "false",
        "source_page": str(page),
        "source_reference": f"Q{num}",
    }


